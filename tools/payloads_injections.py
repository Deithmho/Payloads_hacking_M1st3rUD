AMPLIACIONES = {}


def add(slug, fuente, pruebas):
    if slug in AMPLIACIONES:
        raise ValueError(slug)
    AMPLIACIONES[slug] = [(*p, fuente) if len(p) == 5 else p for p in pruebas]


def ampliar(slug, fuente, pruebas):
    AMPLIACIONES[slug].extend((*p, fuente) if len(p) == 5 else p for p in pruebas)


